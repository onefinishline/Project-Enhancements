// PostgreSQL via node-postgres (pg). Connection from DATABASE_URL, e.g.
//   postgres://enhancements:secret@localhost:5432/project_enhancements
// Tables are created on start if they don't exist (db.init()).
const { Pool, types } = require('pg');

// DATE columns come back as plain 'YYYY-MM-DD' strings, not JS Dates, so a calendar day never shifts by time zone.
types.setTypeParser(1082, (v) => v);

if (!process.env.DATABASE_URL) {
  console.error('[DB] DATABASE_URL is not set. Add it to .env (see .env.example).');
  process.exit(1);
}

const pool = new Pool({
  connectionString: process.env.DATABASE_URL,
  // PGSSL=true for servers that require TLS; PGSSL_REJECT_UNAUTHORIZED=false only for self-signed certificates.
  ssl: process.env.PGSSL === 'true'
    ? { rejectUnauthorized: process.env.PGSSL_REJECT_UNAUTHORIZED !== 'false' }
    : undefined,
  max: Number(process.env.PGPOOL_MAX) || 10,
});
pool.on('error', (err) => console.error('[DB] Idle connection error:', err.message));

// All SQL uses numbered parameters ($1, $2, ...): values are always sent separately from the SQL text.
const query = async (sql, params = []) => (await pool.query(sql, params)).rows;
const one = async (sql, params = []) => (await pool.query(sql, params)).rows[0] || null;
const run = async (sql, params = []) => pool.query(sql, params); // returns { rowCount, rows }

// Runs fn(client) inside a transaction; client has the same query/one/run helpers.
async function tx(fn) {
  const c = await pool.connect();
  const h = {
    query: async (sql, p = []) => (await c.query(sql, p)).rows,
    one: async (sql, p = []) => (await c.query(sql, p)).rows[0] || null,
    run: (sql, p = []) => c.query(sql, p),
  };
  try {
    await c.query('BEGIN');
    const out = await fn(h);
    await c.query('COMMIT');
    return out;
  } catch (err) {
    await c.query('ROLLBACK').catch(() => {});
    throw err;
  } finally {
    c.release();
  }
}

// Yes/no answers are stored as 1/0 (NULL = not answered), as the pages expect.
const SCHEMA = `
  -- Anyone with an allowed email domain can register; is_staff = may verify projects.
  CREATE TABLE IF NOT EXISTS users (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email             TEXT NOT NULL,
    name              TEXT NOT NULL,
    password_hash     TEXT NOT NULL,
    is_staff          BOOLEAN NOT NULL DEFAULT FALSE,
    email_verified_at TIMESTAMPTZ,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now()
  );
  CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower ON users (lower(email));

  -- Single-use links sent by email: purpose 'verify' (confirm address) or 'reset' (new password).
  CREATE TABLE IF NOT EXISTS email_tokens (
    token_hash TEXT PRIMARY KEY,
    user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    purpose    TEXT NOT NULL CHECK (purpose IN ('verify', 'reset')),
    expires_at TIMESTAMPTZ NOT NULL
  );

  CREATE TABLE IF NOT EXISTS sessions (
    token_hash TEXT PRIMARY KEY,
    user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at TIMESTAMPTZ NOT NULL
  );

  CREATE TABLE IF NOT EXISTS projects (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                TEXT NOT NULL,
    parent_project      TEXT,
    short_description   TEXT,
    details             TEXT NOT NULL,
    submitter           TEXT NOT NULL,
    submitter_email     TEXT,
    submitter_phone     TEXT,
    people_needed       INTEGER,
    time_needed         TEXT,
    backend_languages   TEXT,
    frontend_libraries  TEXT,
    mobile_languages    TEXT,
    copyright_handling  TEXT,
    multiple_teams      SMALLINT CHECK (multiple_teams IN (0, 1)),
    multiple_teams_note TEXT,
    security_sensitive  SMALLINT CHECK (security_sensitive IN (0, 1)),
    security_note       TEXT,
    promo_use           TEXT CHECK (promo_use IN ('both', 'descriptions', 'screenshots', 'none')),
    created_by          INTEGER REFERENCES users(id) ON DELETE SET NULL,
    verified_by         INTEGER REFERENCES users(id) ON DELETE SET NULL,
    verified_at         TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now()
  );

  CREATE TABLE IF NOT EXISTS work_requests (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id     INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    organization   TEXT NOT NULL,
    participants   TEXT NOT NULL,
    start_date     DATE,
    end_date       DATE,
    timeframe      TEXT,
    contact_email  TEXT,
    created_by     INTEGER REFERENCES users(id) ON DELETE SET NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
  );
  CREATE INDEX IF NOT EXISTS idx_requests_project ON work_requests(project_id);
`;

// Creates any missing tables. Safe to run on every start.
async function init() {
  await pool.query(SCHEMA);
}

module.exports = { pool, query, one, run, tx, init, end: () => pool.end() };
